import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import open_clip
import medmnist
from medmnist import ChestMNIST
import matplotlib.pyplot as plt
import numpy as np

# 2. Setup Device (GPU if available)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f"Using device: {device}\n")

# 3. Load BiomedCLIP and Transformations
print("Downloading and loading BiomedCLIP...")
model_name = 'hf-hub:microsoft/BiomedCLIP-PubMedBERT_256-vit_base_patch16_224'
model, preprocess_train, preprocess_val = open_clip.create_model_and_transforms(model_name)
model = model.to(device)

# Freeze BiomedCLIP base weights to protect pre-trained medical knowledge
for param in model.parameters():
    param.requires_grad = False

# 4. Download and Prepare the MedMNIST Dataset
print("\nDownloading ChestMNIST dataset...")
chest_train = ChestMNIST(split="train", download=True, size=224)
chest_test = ChestMNIST(split="test", download=True, size=224)

class BiomedCLIPDataset(Dataset):
    def __init__(self, medmnist_data, transform):
        self.data = medmnist_data
        self.transform = transform

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        img, label = self.data[idx]
        img = img.convert("RGB") # BiomedCLIP requires RGB format
        img_tensor = self.transform(img)
        label_tensor = torch.tensor(label).float().squeeze()
        return img_tensor, label_tensor

# Wrap data with BiomedCLIP's preprocessing and load into batches of 64
train_dataset = BiomedCLIPDataset(chest_train, preprocess_val)
train_loader = DataLoader(train_dataset, batch_size=64, shuffle=True)

# 5. Build the Diagnostic Classifier Head
class DiagnosticClassifier(nn.Module):
    def __init__(self, input_dim=512, num_classes=14):
        super().__init__()
        self.classifier = nn.Sequential(
            nn.Linear(input_dim, 256),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(256, num_classes)
        )

    def forward(self, features):
        return self.classifier(features)

diagnostic_head = DiagnosticClassifier(input_dim=512, num_classes=14).to(device)

# 6. Training Loop
criterion = nn.BCEWithLogitsLoss()
optimizer = optim.AdamW(diagnostic_head.parameters(), lr=1e-4)

# Set to 1 epoch for a quick test. You can increase to 3 or 5 later for better accuracy.
epochs = 1
print("\n--- Starting AI Training ---")
diagnostic_head.train()

for epoch in range(epochs):
    total_loss = 0.0
    for batch_idx, (images, labels) in enumerate(train_loader):
        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        # Extract features using frozen BiomedCLIP
        with torch.no_grad():
            features = model.encode_image(images)
            features /= features.norm(dim=-1, keepdim=True)

        # Predict and calculate loss
        predictions = diagnostic_head(features)
        loss = criterion(predictions, labels)

        loss.backward()
        optimizer.step()
        total_loss += loss.item()

        if batch_idx % 100 == 0:
            print(f"Epoch {epoch+1}/{epochs} | Batch {batch_idx}/{len(train_loader)} | Loss: {loss.item():.4f}")

    print(f"*** Epoch {epoch+1} Completed | Average Loss: {total_loss/len(train_loader):.4f} ***\n")

# 7. Model Inference and Visualization (Testing on Unseen Image)
print("--- Running Inference on Test Image ---")
